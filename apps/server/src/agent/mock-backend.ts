/**
 * MockAgentBackend (v0.5 Slice A) — dependency-free, scripted, deterministic.
 *
 * The built-in agent used for tests, demos, and whenever no real ACP binary/key
 * is configured. It speaks only the {@link AgentBackend} contract: on a user
 * message it emits a fixed, inspectable sequence of intents through the sink —
 * it NEVER touches the doc or filesystem itself.
 *
 * Per user message the mock:
 *   1. posts an 'agent' chat reply,
 *   2. proposes a file edit (appends a small function to a target file),
 *   3. proposes ONE destructive tool call (delete a file) with
 *      requiresApproval=true — this exercises the approval gate,
 *   4. proposes a SAFE run-command (no approval) that the host applies at once.
 *
 * IDs are derived from agentId + a per-turn counter so a given turn is fully
 * reproducible, which is what makes the host's behavior assertable in tests.
 */
import type {
  AgentConfig,
  AgentToolCall,
} from '@ice/shared';
import type { AgentBackend, AgentIntentSink, ResolvedHostDeps } from './types.js';
import type { AgentFileOp } from './adapter.js';

/** Knobs so tests/demos can steer what the mock proposes without forking it. */
export interface MockAgentOptions {
  /** File the mock appends its generated function to. */
  targetFile?: string;
  /** File the mock proposes to delete (the gated, destructive call). */
  destructiveTarget?: string;
  /** Safe shell command the mock proposes (auto-applied). */
  safeCommand?: string;
  /** The function source appended on each turn (use {{n}} for the turn index). */
  snippetTemplate?: string;
}

const DEFAULTS: Required<MockAgentOptions> = {
  targetFile: 'src/generated.ts',
  destructiveTarget: 'scratch.tmp',
  safeCommand: 'echo "hello from the mock agent"',
  snippetTemplate:
    '\nexport function mockHelper{{n}}(): string {\n' +
    "  return 'generated by the mock agent (turn {{n}})';\n" +
    '}\n',
};

export class MockAgentBackend implements AgentBackend {
  readonly config: AgentConfig;
  private readonly sink: AgentIntentSink;
  private readonly opts: Required<MockAgentOptions>;
  private turn = 0;
  private started = false;
  private interrupted = false;

  constructor(
    config: AgentConfig,
    sink: AgentIntentSink,
    _deps: ResolvedHostDeps,
    options: MockAgentOptions = {},
  ) {
    this.config = config;
    this.sink = sink;
    this.opts = { ...DEFAULTS, ...options };
  }

  async start(): Promise<void> {
    this.started = true;
    this.sink.emit({ type: 'status', agentId: this.config.agentId, status: 'idle' });
  }

  /**
   * Drive one scripted turn. Synchronous in effect (no real model latency) so
   * tests can await it and immediately assert on doc state. Emits, in order:
   * thinking → message → editing → edit → gated tool-call (awaiting-approval) →
   * safe tool-call. Note the gated call leaves the agent awaiting approval; the
   * safe call is recorded but the host's gate keeps status at awaiting-approval
   * until the human resolves the destructive one (see host/adapter).
   */
  async sendUserMessage(text: string): Promise<void> {
    if (!this.started) throw new Error('MockAgentBackend.sendUserMessage before start()');
    this.interrupted = false;
    const n = (this.turn += 1);
    const agentId = this.config.agentId;
    const idBase = `${agentId}-t${n}`;

    // (0) thinking
    this.sink.emit({ type: 'status', agentId, status: 'thinking' });
    if (this.interrupted) return;

    // (1) chat reply
    this.sink.emit({
      type: 'message',
      message: {
        id: `${idBase}-msg`,
        agentId,
        role: 'agent',
        text:
          `On it — you said: "${truncate(text, 120)}". I'll add a helper to ` +
          `${this.opts.targetFile}, then I'd like to tidy up and run a check.`,
        createdAt: Date.now(),
      },
    });
    if (this.interrupted) return;

    // (2) propose + apply a file edit (append a function). Safe → no gate.
    const editCallId = `${idBase}-edit`;
    const snippet = this.opts.snippetTemplate.replace(/\{\{n\}\}/g, String(n));
    const editOp: AgentFileOp = {
      kind: 'append',
      path: this.opts.targetFile,
      content: snippet,
    };
    this.sink.registerEffect(editCallId, { kind: 'file', op: editOp });
    this.sink.emit({
      type: 'tool-call',
      call: toolCall(editCallId, agentId, 'write_file', {
        path: this.opts.targetFile,
        append: snippet,
      }, false),
    });
    // Breadcrumb for the UI's follow-along.
    this.sink.emit({ type: 'edit', agentId, path: this.opts.targetFile });
    if (this.interrupted) return;

    // (3) propose ONE destructive tool call → requiresApproval. The host gates
    //     this: status becomes awaiting-approval and it is NOT applied until a
    //     human approves.
    const delCallId = `${idBase}-del`;
    this.sink.registerEffect(delCallId, {
      kind: 'file',
      op: { kind: 'delete', path: this.opts.destructiveTarget },
    });
    const delCall = toolCall(
      delCallId,
      agentId,
      'delete_file',
      { path: this.opts.destructiveTarget },
      true,
    );
    this.sink.emit({ type: 'tool-call', call: delCall });
    this.sink.emit({ type: 'awaiting-approval', call: delCall });
    if (this.interrupted) return;

    // (4) propose a SAFE run-command (no approval). Recorded + handed to the
    //     injected terminal (or no-op if none). Does not need a gate.
    const runCallId = `${idBase}-run`;
    this.sink.registerEffect(runCallId, { kind: 'run', command: this.opts.safeCommand });
    this.sink.emit({
      type: 'tool-call',
      call: toolCall(runCallId, agentId, 'run', { command: this.opts.safeCommand }, false),
    });
  }

  /** Host-gated backend: nothing to do here; the adapter owns gate execution. */
  resolveApproval(): void {
    /* no-op by design — see class docstring */
  }

  interrupt(): void {
    this.interrupted = true;
    this.sink.emit({ type: 'status', agentId: this.config.agentId, status: 'idle' });
  }

  async stop(): Promise<void> {
    this.started = false;
    this.interrupted = true;
  }

  /** Test/demo introspection: how many turns this mock has run. */
  get turnsRun(): number {
    return this.turn;
  }
}

function toolCall(
  id: string,
  agentId: string,
  tool: string,
  args: unknown,
  requiresApproval: boolean,
): AgentToolCall {
  return { id, agentId, tool, args, requiresApproval, status: 'proposed' };
}

function truncate(s: string, max: number): string {
  return s.length <= max ? s : `${s.slice(0, max - 1)}…`;
}
